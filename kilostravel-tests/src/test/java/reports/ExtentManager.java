package reports;

import com.aventstack.extentreports.ExtentReports;
import com.aventstack.extentreports.reporter.ExtentSparkReporter;
import com.aventstack.extentreports.reporter.configuration.Theme;

import java.io.File;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

/**
 * Singleton factory for the ExtentReports instance.
 * Each test run writes a timestamped HTML file under target/reports/.
 */
public class ExtentManager {

    private static ExtentReports extent;
    private static String reportPath;

    private ExtentManager() {}

    public static synchronized ExtentReports getInstance() {
        if (extent == null) {
            // ── Build timestamped path under target/reports/ ──────────────────
            String timestamp = LocalDateTime.now()
                    .format(DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss"));
            File reportsDir = new File("target/reports");
            reportsDir.mkdirs();
            reportPath = "target/reports/ExtentReport_" + timestamp + ".html";

            // ── HTML reporter configuration ───────────────────────────────────
            ExtentSparkReporter reporter = new ExtentSparkReporter(reportPath);
            reporter.config().setTheme(Theme.DARK);
            reporter.config().setDocumentTitle("KilosTravel Test Report");
            reporter.config().setReportName("KilosTravel QA Suite — Selenium + Cucumber");
            reporter.config().setTimeStampFormat("dd MMM yyyy HH:mm:ss");

            // ── Attach reporter and set metadata ─────────────────────────────
            extent = new ExtentReports();
            extent.attachReporter(reporter);
            extent.setSystemInfo("Application", "KilosTravel / AirWeight");
            extent.setSystemInfo("Environment", "Local — http://localhost:3000");
            extent.setSystemInfo("Backend API", "http://localhost:8000");
            extent.setSystemInfo("Browser", "Google Chrome (latest)");
            extent.setSystemInfo("Framework", "Selenium 4 + Cucumber 7 + JUnit 4");
            extent.setSystemInfo("Tester", "QA Team");
        }
        return extent;
    }

    /** Returns the path of the report file generated by this run. */
    public static String getReportPath() {
        return reportPath;
    }
}
